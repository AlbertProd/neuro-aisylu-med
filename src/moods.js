export const MOODS = [
  ...positive.map(([name, instruction], index) => ({ id: index, kind: 'positive', name, instruction })),
  ...negative.map(([name, instruction], index) => ({ id: index + 20, kind: 'negative', name, instruction })),
];

export function nextMood(previousId = -1, pick = randomInt) {
  const choices = MOODS.filter((mood) => mood.id !== previousId);
  return { ...choices[pick(choices.length)], remaining: pick(3, 8) };
}
